/**
 * Icon packs, in Themes+'s format (nexpid/ThemesPlus), written fresh for Revenge Next.
 *
 * A pack is a folder laid out like Discord's assets, so an icon's place in it follows from the
 * asset itself: `/assets/design/components/Icon/native/redesign/generated/images` + `BellIcon.png`
 * is at `<load>design/components/Icon/native/redesign/generated/images/BellIcon<suffix>.png`.
 * nexpid publishes a list of the files in each pack (the `iconpack-trees` branch), so only icons a
 * pack actually has are swapped; the rest stay Discord's.
 *
 * Themes+ does the swap by replacing React Native's `Image`. This uses Revenge Next's own
 * `addAssetOverride` instead: Revenge registers a `resolveAssetSource` transformer that hands back
 * the override, so anything drawing a Discord asset by number gets the pack's copy. On 348.5 every
 * redesign icon is drawn that way: `BellIcon` and the other 372 icon components render
 * `BaseIconImage`, which is an `Image` with the asset number as `source`. Icons are tinted by
 * Discord (`tintColor`), so two-tone packs come out in one colour, as they did in Themes+.
 */

import { patch, report, settings } from './state'
import type { IconPack } from '../types'

const LIST_URL =
	'https://raw.githubusercontent.com/nexpid/ThemesPlus/main/iconpacks/list.json'
const treeUrl = (id: string) =>
	`https://raw.githubusercontent.com/nexpid/ThemesPlus/iconpack-trees/${id}.txt`

/** Where Discord's redesign icons live. A pack with no file list only swaps these. */
export const ICON_FOLDER =
	'design/components/Icon/native/redesign/generated/images'

async function text(url: string): Promise<string> {
	const response = await fetch(url, { cache: 'no-store' } as RequestInit)
	if (!response.ok) throw new Error(`HTTP ${response.status}`)
	return response.text()
}

function isPack(json: any): json is IconPack {
	return (
		typeof json === 'object' &&
		json !== null &&
		typeof json.name === 'string' &&
		typeof json.load === 'string' &&
		/^https?:\/\//i.test(json.load)
	)
}

function normalise(pack: IconPack, id = pack.id): IconPack {
	return {
		...pack,
		id,
		name: pack.name.trim(),
		load: pack.load.endsWith('/') ? pack.load : `${pack.load}/`,
	}
}

/** Themes+'s pack list, downloaded again and kept for next time. */
export async function refreshPackList(): Promise<IconPack[]> {
	const json = JSON.parse(await text(LIST_URL))
	const list = (Array.isArray(json?.list) ? json.list : [])
		.filter(isPack)
		.map((pack: IconPack) => normalise(pack))
	if (list.length) patch({ iconPackList: list })
	return list
}

/**
 * Our own packs, drawn from Iconify sets (bleelblep/discord-icon-packs, generated by its
 * `scripts/`). Same format as Themes+'s list; each pack carries its own `tree`.
 */
const INCLUDED_LIST_URL =
	'https://raw.githubusercontent.com/bleelblep/discord-icon-packs/main/list.json'

export async function refreshIncludedList(): Promise<IconPack[]> {
	const json = JSON.parse(await text(INCLUDED_LIST_URL))
	const list = (Array.isArray(json?.list) ? json.list : [])
		.filter(isPack)
		.map((pack: IconPack) => normalise(pack))
	if (list.length) patch({ includedPackList: list })
	return list
}

/** Every pack there is to choose: ours, Themes+'s, then the ones added by link. */
export function allPacks(): IconPack[] {
	const { includedPackList = [], iconPackList, iconPacks } = settings()
	const listed = [...includedPackList, ...iconPackList]
	return [
		...listed,
		...iconPacks.filter(pack => !listed.some(entry => entry.id === pack.id)),
	]
}

/**
 * Packs that start hidden because another pack already looks nearly the same. Discord tints
 * every icon in one colour, so a duotone or two-tone pack comes out close to its plain one.
 * The user can show any of them again from the Icons page.
 */
export const HIDDEN_BY_DEFAULT: ReadonlySet<string> = new Set([
	'solarduotone', // Solar, second tone lost to the tint
	'solarbroken', // Solar again, dashed
	'materialtwotone', // close to MD3
	'iconsaxbulk', // Iconsax two-tone; Rosiecord Iconsax covers it
	'md3legacy', // superseded by MD3 (Rounded)
	'bleelblep-icon-park-twotone', // IconPark Outline/Solid with a lighter second tone
])

/** Whether the Icons page lists a pack. The one in use and ones added by link always are. */
export function isPackShown(pack: IconPack): boolean {
	const s = settings()
	if (
		pack.id === s.selectedIconPack ||
		s.iconPacks.some(entry => entry.id === pack.id)
	)
		return true
	return s.packShown?.[pack.id] ?? !HIDDEN_BY_DEFAULT.has(pack.id)
}

export function setPackShown(id: string, shown: boolean) {
	patch({ packShown: { [id]: shown } })
}

/** Whether a pack is one of ours. */
export function isIncluded(id: string): boolean {
	return (settings().includedPackList ?? []).some(pack => pack.id === id)
}

export function findPack(id: string): IconPack | undefined {
	return allPacks().find(pack => pack.id === id)
}

/** A pack's file list: nexpid's for the listed ones, its own `tree` for one added by link. */
const trees = new Map<string, string[]>()

export async function packTree(pack: IconPack): Promise<string[]> {
	const known = trees.get(pack.id)
	if (known) return known
	const listed = settings().iconPackList.some(entry => entry.id === pack.id)
	const url = pack.tree ?? (listed ? treeUrl(pack.id) : undefined)
	if (!url) return []
	const tree = (await text(url))
		.replace(/\r/g, '')
		.split('\n')
		.map(line => line.trim())
		.filter(Boolean)
	trees.set(pack.id, tree)
	return tree
}

/** The pack's copy of a Discord icon by name, for previews. */
export function iconUrl(pack: IconPack, name: string): string {
	return `${pack.load}${ICON_FOLDER}/${name}${pack.suffix ?? ''}.png`
}

/** A link to one pack's .json, or to a whole list like Themes+'s. */
export async function installIconPack(
	input: string,
): Promise<{ name: string }> {
	const url = input.trim()
	if (!/^https?:\/\//i.test(url))
		throw new Error('Paste a link starting with https://')
	let json: any
	try {
		json = JSON.parse(await text(url))
	} catch (error) {
		throw new Error(
			`Couldn't download an icon pack from that link (${(error as Error)?.message ?? error})`,
		)
	}

	const found: IconPack[] = isPack(json)
		? [normalise(json, url)]
		: (Array.isArray(json?.list) ? json.list : [])
				.filter(isPack)
				.map((pack: IconPack) =>
					normalise(pack, `${url}#${pack.id ?? pack.name}`),
				)
	if (!found.length)
		throw new Error("That link isn't a Themes+ icon pack or pack list")

	const added = found.filter(pack => !findPack(pack.id))
	if (!added.length) throw new Error('Those icon packs are already there')
	patch({ iconPacks: [...settings().iconPacks, ...added] })
	return {
		name: added.length === 1 ? added[0].name : `${added.length} icon packs`,
	}
}

export function removeIconPack(id: string) {
	if (settings().selectedIconPack === id) selectIconPack('')
	patch({ iconPacks: settings().iconPacks.filter(pack => pack.id !== id) })
}

// ---- swapping ---------------------------------------------------------------------------------------

/** Every override we added, so turning a pack off takes exactly those back. */
let overridden: any[] = []
/** Their asset ids, for `isSwapped`. */
const swappedIds = new Set<number>()

/** Whether an image source is a Discord asset the pack in use swapped. */
export function isSwapped(source: unknown): boolean {
	return typeof source === 'number' && swappedIds.has(source)
}

function clearOverrides() {
	const assets = revenge.assets as any
	for (const asset of overridden) {
		try {
			assets.removeAssetOverride(asset)
		} catch {
			/* already gone */
		}
	}
	overridden = []
	swappedIds.clear()
}

/** Where an asset would be in a pack, as Themes+ worked it out, `../` folders becoming `_/`. */
function packPath(asset: any, suffix: string): string | undefined {
	const location: unknown = asset?.httpServerLocation
	if (typeof location !== 'string' || typeof asset.name !== 'string')
		return undefined
	const path = [
		...location.split('/').slice(2),
		`${asset.name}${suffix}.${asset.type}`,
	].join('/')
	return path.startsWith('../') ? `_/${path.slice(3)}` : path
}

/**
 * How many pixels per point the pack's images are. Packs copy Discord's icons at one density (the
 * listed ones at 72 px for a 24 pt icon, the `@2x` ones at 48), but the override carries only the
 * point size. Discord's JS `Image` sizes icons from its style, so it doesn't matter there; native
 * parts that draw the image at its own size showed each icon at 3x, too large and cut off
 * (2026-09-28). So the scale is measured once, from the pack's bell, when the pack is chosen.
 */
const DEFAULT_SCALE = 3

async function measureScale(pack: IconPack, tree: string[]): Promise<number> {
	const suffix = pack.suffix ?? ''
	const name =
		['BellIcon', 'SettingsIcon', 'ChatIcon'].find(
			icon =>
				!tree.length || tree.includes(`${ICON_FOLDER}/${icon}${suffix}.png`),
		) ?? 'BellIcon'
	const points = (revenge.assets as any).getAssetByName(name, 'png')?.width
	if (typeof points !== 'number' || points <= 0) return DEFAULT_SCALE
	const { Image } = revenge.react.ReactNative as any
	const pixels = await new Promise<number>(resolve => {
		const timer = setTimeout(() => resolve(0), 8000)
		try {
			Image.getSize(
				iconUrl(pack, name),
				(width: number) => {
					clearTimeout(timer)
					resolve(width)
				},
				() => {
					clearTimeout(timer)
					resolve(0)
				},
			)
		} catch {
			clearTimeout(timer)
			resolve(0)
		}
	})
	if (!pixels) return DEFAULT_SCALE
	return Math.min(4, Math.max(1, Math.round((pixels / points) * 2) / 2))
}

/** Points every Discord asset the pack has at the pack's copy. Returns how many. */
function applyPack(pack: IconPack, tree: string[], scale: number): number {
	clearOverrides()
	const assets = revenge.assets as any
	const has = new Set(tree)
	const suffix = pack.suffix ?? ''
	for (const asset of assets.getPackagerAssets() as Iterable<any>) {
		const path = packPath(asset, suffix)
		if (!path) continue
		if (has.size ? !has.has(path) : !path.startsWith(`${ICON_FOLDER}/`))
			continue
		const override = {
			name: asset.name,
			type: asset.type,
			width: asset.width,
			height: asset.height,
			scale,
			uri: `${pack.load}${path}`,
		}
		assets.addAssetOverride(asset, override)
		overridden.push(asset)
		// Revenge sets `id` on Discord's assets as they register; the lookup is the fallback.
		const id =
			typeof asset.id === 'number'
				? asset.id
				: assets.getAssetIdByName(asset.name, asset.type)
		if (typeof id === 'number') swappedIds.add(id)
	}
	return overridden.length
}

/**
 * Downloads the pack's file list, swaps the icons and remembers the choice; `''` puts Discord's
 * icons back. Icons already on screen change when they're next drawn, so a reload shows them all.
 */
export async function selectIconPack(id: string): Promise<number> {
	if (!id) {
		clearOverrides()
		patch({
			selectedIconPack: '',
			iconPack: undefined,
			iconTree: [],
			iconScale: undefined,
		})
		report('icon pack', "Discord's own")
		return 0
	}
	const pack = findPack(id)
	if (!pack) throw new Error('That icon pack is no longer there')
	let tree: string[]
	try {
		tree = await packTree(pack)
	} catch (error) {
		throw new Error(
			`Couldn't download the pack's file list (${(error as Error)?.message ?? error})`,
		)
	}
	const scale = await measureScale(pack, tree)
	const count = applyPack(pack, tree, scale)
	if (!count) throw new Error("None of Discord's icons are in that pack")
	patch({
		selectedIconPack: id,
		iconPack: pack,
		iconTree: tree,
		iconScale: scale,
	})
	report('icon pack', `${pack.name}: ${count} icons swapped at ${scale}x`)
	return count
}

/** How many icons the pack in use swapped, for its page. */
export function swappedCount(): number {
	return overridden.length
}

/** At launch, from what was stored: no download before the first screen. */
export function applyIconsAtLaunch() {
	const { selectedIconPack, iconPack, iconTree, iconScale } = settings()
	if (!selectedIconPack || !iconPack) return
	const scale = iconScale ?? DEFAULT_SCALE
	const count = applyPack(iconPack, iconTree, scale)
	report(
		'icon pack',
		`${iconPack.name}: ${count} icons swapped at launch, at ${scale}x`,
	)
}

export function clearIcons() {
	clearOverrides()
}
